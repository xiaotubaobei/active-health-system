import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import test from 'node:test';
import assert from 'node:assert/strict';

test('service worker sends private data and mutations directly to network without touching caches', async () => {
  const listeners = {}, requests = [];
  const context = vm.createContext({ URL, Request, Response,
    self: { registration: { scope: 'https://health.test/' }, location: { origin: 'https://health.test' },
      addEventListener: (name, handler) => { listeners[name] = handler; } },
    fetch: async request => { requests.push(request); return new Response('network'); },
    caches: new Proxy({}, { get() { throw new Error('private request touched cache'); } }),
  });
  vm.runInContext(readFileSync(new URL('../public/sw.js', import.meta.url), 'utf8'), context);
  for (const [path, method] of [['/api/auth/me', 'GET'], ['/api/sessions/1/report', 'GET'],
    ['/uploads/private.mp4', 'GET'], ['/api/sessions', 'POST']]) {
    let response;
    const request = new Request('https://health.test' + path, { method });
    listeners.fetch({ request, respondWith: promise => { response = promise; } });
    assert.equal(await (await response).text(), 'network');
    assert.equal(requests.at(-1), request);
  }
});

